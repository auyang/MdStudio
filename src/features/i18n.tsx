export function translate(locale: AppLocale, source: string, values?: MessageValues): string {
  let message = locale === 'zh-CN' ? source : translations[source]?.[locale === 'en' ? 0 : 1] ?? source
  if (values) {
    message = message.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : placeholder,
    )
  }
  return message
}

const LocaleContext = createContext<AppLocale>(DEFAULT_APP_LOCALE)

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>
}

export function useI18n() {
  const locale = useContext(LocaleContext)
  return useCallback((source: string, values?: MessageValues) => translate(locale, source, values), [locale])
}
